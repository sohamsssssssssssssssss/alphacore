def erratum(a) -> str:
    rel = "research/METRICS_ERRATUM.md"
    body, in_table = [], False
    for line in a.text(rel).splitlines():
        if line.startswith("| Report / artifact"):
            in_table = True
            continue
        if not in_table or line.startswith("|---"):
            continue
        if not line.startswith("|"):
            break
        report, branch, point, ci_cell, outside, defs = [c.strip() for c in line.strip("|").split("|")]
        try:
            point_s = a.val(float(point), rel, "v1 point Sharpe", sh, latex=False)
        except ValueError:
            point_s = a.val(point, rel, "v1 point Sharpe")
        nums = re.fullmatch(r"\[(-?[\d.]+), (-?[\d.]+)\]", ci_cell)
        ci_s = (a.val([float(nums.group(1)), float(nums.group(2))], rel, "v1 CI", ci, latex=False)
                if nums else a.val(ci_cell, rel, "v1 CI"))
        body.append([a.val(plain(report), rel, "Report / artifact") + " (" + a.val(branch, rel, "Branch") + ")",
                     point_s, ci_s, a.val(outside, rel, "Point outside CI?"),
                     a.val(defs, rel, "Point / CI definition")])
    if not body:
        raise MissingSource("erratum table not found in research/METRICS_ERRATUM.md")
    return table("Yllll", ["Report (branch)", "Point", "CI", "Point outside CI?", "Point / CI definition"], body,
                 "Metrics erratum: v1 point and interval pairs and the definition each used.",
                 "tab:erratum", env="xltabular")


def benchmarks(a) -> str:
    rel = "engine/benchmarks/RESULTS.md"
    text = a.text(rel)
    runs = re.findall(r"^## (\S+)\n\nMachine: (.+?)\.\nCompiler: (.+?)\. Build: (.+?)\n\n\| Benchmark \| ns/op \|\n"
                      r"\|---\|---:\|\n((?:\|.*\|\n)+)\n(.+)", text, re.M)
    if not runs:
        raise MissingSource("no recorded run in engine/benchmarks/RESULTS.md")
    body, notes = [], []
    for when, machine, compiler, build, rows, caveat in runs:
        w = a.val(when, rel, "run timestamp (UTC)")
        for row in rows.strip().splitlines():
            name, ns = [c.strip() for c in row.strip("|").split("|")]
            body.append([w, a.val(name, rel, "Benchmark"), a.val(ns, rel, "ns/op")])
        notes.append(f"Run {w}: " + a.val(machine, rel, "Machine") + "; " + a.val(compiler, rel, "Compiler")
                     + "; " + a.val(build.rstrip("."), rel, "Build") + ". " + a.val(caveat, rel, "caveat line"))
    return table("lYr", ["Run (UTC)", "Benchmark", "ns/op"], body,
                 "Recorded engine micro-benchmarks, as measured (no speed comparison claimed).",
                 "tab:benchmarks", " ".join(notes))


