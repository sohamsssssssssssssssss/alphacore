# ── Macros ─────────────────────────────────────────────────────────────

def macros(a) -> str:
    out = [HEADER.rstrip()]

    def m(name: str, rendered: str) -> None:
        assert re.fullmatch(r"[A-Za-z]+", name), name
        out.append(rf"\newcommand{{\{name}}}{{{rendered}}}")

    def shm(x):
        return rf"\ensuremath{{{x:.2f}}}"

    rows = v2_rows(a)
