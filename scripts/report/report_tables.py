def cfg_info(a, rel: str) -> tuple[str, list[str]]:
    """(constants 'A=1, B=2', invariants/properties) parsed from a TLC .cfg file."""
    consts, checks, section = [], [], None
    for line in a.text(rel).splitlines():
        s = line.strip()
        if re.fullmatch(r"[A-Z_]+(?: \w+)?", s) and s.split()[0].isupper():
            section = s.split()[0]
            continue
        if not s:
            continue
        if section == "CONSTANTS":
            consts.append(s.replace(" ", ""))
        elif section in ("INVARIANT", "INVARIANTS"):
            checks.append(s)
        elif section in ("PROPERTY", "PROPERTIES"):
            checks.append(s + " (property)")
    return ", ".join(consts), checks


def tla_rows(a) -> list[dict]:
    ci_data = a.json(CI_TLC)
    run = ci_data["run_id"]
    rows = []
    for m in ci_data["models"]:
        cfg = f'{m["dir"]}/{m["config"]}'
        consts, checks = cfg_info(a, cfg)
        rows.append(dict(key=("Specs" if m["dir"] == "specs/tla" else "Engine") + m["spec"][:-4],
                         spec=f'{m["dir"]}/{m["spec"]}', cfg=cfg, consts=consts, checks=checks,
                         gen=m["generated"], dist=m["distinct"], result=m["result"],
                         where=f"CI run {run}", src=CI_TLC))
    # Local run of the fenced model recorded in specs/README.md
    readme = a.text("specs/README.md")
    m = re.search(r"passes with the same constants \(([^)]*)\): ([\d,]+)\s+states generated, ([\d,]+) distinct", readme)
    fenced = next(r for r in rows if r["spec"] == "specs/tla_engine_models/PrimaryBackup.tla")
    if m and (int(m.group(2).replace(",", "")), int(m.group(3).replace(",", ""))) == (fenced["gen"], fenced["dist"]):
        fenced["where"] += "; local (specs/README.md)"
    # Earlier-run counts quoted in an old report for specs CI now runs at a different size
    for line in a.text("ALPHACORE_STATUS_REPORT.md").splitlines():
        e = re.match(r"\| (\w+\.tla) \|[^|]*\| ([\d,]+) generated, ([\d,]+) distinct \| ([^|]+) \|", line)
        if not e:
            continue
        gen, dist = (int(e.group(i).replace(",", "")) for i in (2, 3))
        spec = f"specs/tla_engine_models/{e.group(1)}"
        if any(r["spec"] == spec and (r["gen"], r["dist"]) == (gen, dist) for r in rows):
            continue
        rows.append(dict(key="Earlier" + e.group(1)[:-4], spec=spec, cfg="not recorded", consts="",
                         checks=[c.strip() for c in e.group(4).split(",")], gen=gen, dist=dist,
                         result="no error (earlier run)", where="earlier run (ALPHACORE_STATUS_REPORT.md)",
                         src="ALPHACORE_STATUS_REPORT.md", raw=(e.group(2), e.group(3))))
    # Unfenced model: the recorded counterexample trace
    trace = "specs/tla_engine_models/history/SinglePrimaryPerEpoch.txt"
    t = a.text(trace)
    tm = re.search(r"(\d+) states generated, (\d+) distinct states found", t)
    inv = re.search(r"Invariant (\w+) is violated", t).group(1)
    consts, checks = cfg_info(a, "specs/tla_engine_models/history/ModelPrimaryBackup.cfg")
    rows.append(dict(key="Unfenced", spec="specs/tla_engine_models/history/PrimaryBackup.tla",
                     cfg="specs/tla_engine_models/history/ModelPrimaryBackup.cfg", consts=consts, checks=checks,
                     gen=int(tm.group(1)), dist=int(tm.group(2)), result=f"{inv} violated",
                     where="local (history/SinglePrimaryPerEpoch.txt)", src=trace))
    return rows


def tla_models(a) -> str:
    body = []
    for r in tla_rows(a):
        if r["cfg"] == "not recorded":
            cfg = a.val("not recorded", r["src"], "config (absent from source)")
        else:
            cfg = r"\texttt{" + a.val(r["cfg"].split("/")[-1], r["cfg"], "config file name") + "}"
        if r["consts"]:
            cfg += " (" + a.val(r["consts"], r["cfg"], "CONSTANTS") + ")"
        checks_src = r["cfg"] if r["cfg"] != "not recorded" else r["src"]
        body.append([r"\texttt{" + a.val(r["spec"].replace("specs/", ""), r["src"], "spec path") + "}", cfg,
                     a.val(r["gen"], r["src"], "states generated", count),
                     a.val(r["dist"], r["src"], "distinct states", count),
                     a.val(", ".join(r["checks"]), checks_src, "INVARIANT(S)/PROPERTY"),
                     a.val(r["result"], r["src"], "result"), a.val(r["where"], r["src"], "where run")])
    return table("YYrrYll", ["Spec", "Config", "Generated", "Distinct", "Invariants checked", "Result", "Where run"],
                 body, "Bounded model checking with TLC: every model, configuration and state count. "
                       "Rows marked earlier run quote an older report and are not what CI runs now.",
                 "tab:tla-models", env="xltabular")


