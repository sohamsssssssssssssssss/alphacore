"""Table and macro generators (LaTeX fragments in report/generated/).

Every value is read from a tracked file through Asset.val(); nothing numeric is
typed here. Sharpe/CI values are rounded to 2 decimals and state counts get
thousands separators only at render time.
"""
from __future__ import annotations

import re

from report_common import ROOT, MissingSource, tex

V2 = "research/v2"
README = "README.md"
CI_TLC = "report/data/ci_tlc.json"
TEST_COUNTS = "report/data/test_counts.json"
PROVENANCE_DOCS = {f"{V2}/k12_basket.json": "research/K12_BASKET_PROVENANCE.md"}
CATEGORIES = ["significantly negative", "inconclusive", "exploratory, no edge shown", "not re-run"]
HEADER = "% Generated by scripts/report/build_assets.py; do not edit. Sources: report/SOURCES.md\n"


def sh(x: float) -> str:
    return f"${x:.2f}$"


def ci(pair) -> str:
    return f"$[{pair[0]:.2f}, {pair[1]:.2f}]$"


def count(n) -> str:
    return f"{int(n):,}"


def natural(name: str):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", name)]


# ── research/v2 rows ───────────────────────────────────────────────────

def readme_experiments(a) -> list[dict]:
    """Rows of the README experiment list: number, name, protocol cell, v2 cell."""
    rows = []
    for line in a.text(README).splitlines():
        m = re.match(r"\| (\d+(?:–\d+)?) \| (.+?) \| (.+?) \| (.+?) \| (.+?) \|$", line)
        if m:
            rows.append(dict(num=m.group(1), name=m.group(2), protocol=m.group(3), v2=m.group(5)))
    if not rows:
        raise MissingSource("experiment table not found in README.md")
    return rows


def md_links(cell: str) -> list[tuple[str, str]]:
    return re.findall(r"\[([^\]]+)\]\(([^)]+)\)", cell)


def plain(cell: str) -> str:
    return re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", cell).replace("`", "")


def category(a, rel: str, d: dict) -> str:
    if "status" in d:
        return "not re-run"
    lo, hi = primary_ci(d)
    if hi < 0:
        return "significantly negative"
    if lo > 0:
        raise ValueError(f"{rel}: primary CI excludes zero on the positive side; no category rule, needs a human decision")
    doc = PROVENANCE_DOCS.get(rel)
    if doc:
        label = re.search(r"label this result\s+\*\*(.+?)\*\*", a.text(doc), re.S).group(1)
        if "exploratory" in label:
            a.val(label, doc, "provenance label (\"label this result **...**\")")
            return "exploratory, no edge shown"
    return "inconclusive"


def primary_ci(d: dict):
    conv = d["primary_convention"]
    if conv == "zero-rf":
        sharpe, pair = d["v2_sharpe_zero_rf"], d["v2_ci_zero_rf"]
    elif conv.startswith("excess"):
        sharpe, pair = d["v2_sharpe"], d["v2_ci"]
    else:
        raise ValueError(f"unknown primary convention {conv!r}")
    assert sharpe == d["primary_sharpe"], "primary_sharpe disagrees with its convention's field"
    return pair


def primary_fields(d: dict) -> tuple[str, str]:
    return ("v2_sharpe_zero_rf", "v2_ci_zero_rf") if d["primary_convention"] == "zero-rf" else ("v2_sharpe", "v2_ci")


def v2_rows(a) -> list[dict]:
    """research/v2 results, identical runs merged, plus README rows that were never re-run."""
    files = sorted((p.relative_to(ROOT).as_posix() for p in (ROOT / V2).glob("*.json")),
                   key=lambda r: natural(r.split("/")[-1]))
    rows: list[dict] = []
    for rel in files:
        d = a.json(rel)
        row = {"rel": rel, "d": d, "names": [d["experiment"]], "rels": [rel], "category": category(a, rel, d)}
        key = tuple(d.get("returns") or ())
        twin = next((r for r in rows if key and tuple(r["d"].get("returns") or ()) == key), None)
        if twin:
            twin["names"].append(d["experiment"])
            twin["rels"].append(rel)
            continue
        rows.append(row)
    for r in readme_experiments(a):
        if not md_links(r["v2"]):  # never re-run: no v2 artifact linked
            rows.append({"rel": README, "d": {"status": r["v2"]}, "names": [f'{r["num"]} {r["name"]}'],
                         "rels": [README], "category": "not re-run", "readme": True})
    rows.sort(key=lambda r: (CATEGORIES.index(r["category"]), natural(r["names"][0])))
    return rows


def name_cell(a, r) -> str:
    parts = []
    for n, rel in zip(r["names"], r["rels"]):
        field = "experiment table: # and Experiment" if r.get("readme") else "experiment"
        parts.append(a.val(n, rel, field))
    return " / ".join(parts) + ("$^{a}$" if len(parts) > 1 else "")


def merged_note(a, rows) -> str:
    notes = []
    for r in rows:
        if len(r["rels"]) > 1:
            files = ", ".join(r"\texttt{" + a.val(rel.split("/")[-1], rel, "returns (identical series)") + "}"
                              for rel in r["rels"])
            notes.append(r"$^{a}$ Same run: identical return series in " + files + ". Shown once.")
    return " ".join(notes)


def table(spec: str, header: list[str], body: list[list[str]], caption: str, label: str,
          notes: str = "", env: str = "tabularx") -> str:
    lines = [HEADER]
    if env == "xltabular":
        lines += [r"{\footnotesize", rf"\begin{{xltabular}}{{\textwidth}}{{{spec}}}",
                  rf"\caption{{{caption}}}\label{{{label}}}\\", r"\toprule",
                  " & ".join(header) + r" \\", r"\midrule", r"\endhead"]
    else:
        lines += [r"\begin{table}[htbp]", r"\centering\footnotesize",
                  rf"\begin{{tabularx}}{{\textwidth}}{{{spec}}}", r"\toprule",
                  " & ".join(header) + r" \\", r"\midrule"]
    lines += [" & ".join(row) + r" \\" for row in body]
    lines.append(r"\bottomrule")
    if env == "xltabular":
        lines += [r"\end{xltabular}", "}"]
        if notes:
            lines += [r"{\footnotesize\noindent " + notes + r"\par}"]
    else:
        lines.append(r"\end{tabularx}")
        if notes:
            lines += [r"\par\smallskip{\raggedright " + notes + r"\par}"]
        lines += [rf"\caption{{{caption}}}\label{{{label}}}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def conf_level(a) -> str:
    rel = f"{V2}/experiment_3_cross_sectional.json"
    return a.val(int(round(a.json(rel)["consistent_bootstrap"]["confidence"] * 100)), rel,
                 "consistent_bootstrap.confidence (x100)")


def results_main(a) -> str:
    rows = v2_rows(a)
    level = conf_level(a)
    body = []
    for r in rows:
        d, rel = r["d"], r["rel"]
        if "status" in d:
            field = "experiment table: v2" if r.get("readme") else "status"
            reason = a.val(plain(d["status"]), rel, field)
            body.append([name_cell(a, r), r"\emph{" + reason + "}", "n/a", "n/a", "n/a", r["category"]])
            continue
        sf, cf = primary_fields(d)
        body.append([name_cell(a, r), a.val(d["deployed_fraction"]["summary"], rel, "deployed_fraction.summary"),
                     a.val(d["primary_convention"], rel, "primary_convention"),
                     a.val(d[sf], rel, sf, sh, latex=False), a.val(d[cf], rel, cf, ci, latex=False), r["category"]])
    rerun = [r for r in rows if r["category"] != "not re-run"]
    caption = (f"Primary-convention annualised Sharpe ratio and {level}\\% stationary-bootstrap interval per "
               f"distinct configuration. Category rule: interval entirely below zero is significantly negative; "
               f"an interval that includes zero is inconclusive, or exploratory if the result has an "
               f"exploratory provenance label.")
    notes = merged_note(a, rows)
    return table("lYllll", ["Experiment", "Deployed (from code)", "Primary", "Sharpe", f"{level}\\% CI", "Category"],
                 body, caption, "tab:results-main", notes)


def results_both_conventions(a) -> str:
    rows = v2_rows(a)
    level = conf_level(a)
    rf_rel = f"{V2}/experiment_3_cross_sectional.json"
    rf = a.val(a.json(rf_rel)["metric_definition"]["annual_risk_free"], rf_rel, "metric_definition.annual_risk_free")
    body = []
    for r in rows:
        d, rel = r["d"], r["rel"]
        if "status" in d:
            body.append([name_cell(a, r)] + ["n/a"] * 4)
            continue
        body.append([name_cell(a, r)] + [a.val(d[f], rel, f, fmt, latex=False) for f, fmt in
                                         (("v2_sharpe_zero_rf", sh), ("v2_ci_zero_rf", ci), ("v2_sharpe", sh), ("v2_ci", ci))])
    return table("Yllll", ["Experiment", "Sharpe, zero-rf", f"{level}\\% CI, zero-rf",
                           f"Sharpe, rf$=${rf}", f"{level}\\% CI, rf$=${rf}"], body,
                 "Both Sharpe conventions for every row; each interval uses the same convention as its point.",
                 "tab:both-conventions", merged_note(a, rows))


